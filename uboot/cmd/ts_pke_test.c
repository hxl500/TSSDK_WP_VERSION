s32 ts_pke_rsa_enc_dec_test(void)
{
	u32 e[128]={0};
	u32 d[128];
	u32 n[128];
	u32 in[128];
	u32 out[128];
	u32 out2[128];
	u32 eBitLen=17;
	u32 nBitLen=1024;
	u8 ret;

	//RSA NON-CRT
	nBitLen=1024;//2048;//
	ret = RSA_GetKey(e, d, n, eBitLen, nBitLen);
	if(ret)
	{
		printf("\r\n RSA_GetKey failure, ret = %d", ret);
		return 1;
	}

	//test encrypt & decrypt
	uint32_set(in, 0x1, (nBitLen+0x1F)>>5);
	ret = RSA_ModExp(in, d, n, out, get_valid_bits(d, (nBitLen+0x1F)>>5), nBitLen);
	if(ret)
	{
		printf("\r\n RSA_ModExp error, ret = %d", ret);
		return 1;
	}

	ret = RSA_ModExp(out, e, n, out2, eBitLen, nBitLen);
	if(ret)
	{
		printf("\r\n RSA_ModExp error, ret = %d", ret);
		return 1;
	}

	if(uint32_BigNumCmp(out2, (nBitLen+0x1F)>>5, in, (nBitLen+0x1F)>>5))
	{
		printf("\r\n RSA encrypt & decrypt error");
		print_BN_buf_U32(in, (nBitLen+0x1F)>>5, "in");
		print_BN_buf_U32(out, (nBitLen+0x1F)>>5, "out");
		print_BN_buf_U32(out2, (nBitLen+0x1F)>>5, "out2");
		print_BN_buf_U32(e, (eBitLen+0x1F)>>5, "e");
		print_BN_buf_U32(d, (nBitLen+0x1F)>>5, "d");
		print_BN_buf_U32(n, (nBitLen+0x1F)>>5, "n");
		return 1;
	}

	return 0;
}

