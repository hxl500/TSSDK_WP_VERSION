static int YUV_Draw_HorLine_neon(unsigned char *YuvBuf, int ImgW, int ImgH, int fmt, int SPntX, int SPntY, int EPntX, int EPntY, int Color)
{
	int ret = -1;
	uint8_t y = s_color_table[Color].Y;
	uint8_t u = s_color_table[Color].U;
	uint8_t v = s_color_table[Color].V;
	uint8_t *y_addr = YuvBuf + SPntY * ImgW + SPntX;
	uint8_t *yn_addr = y_addr + ImgW;
	uint8_t *uv_addr = YuvBuf + ImgW * ImgH + (SPntY >> 1) * ImgW + SPntX;

	int i = 0, j = 0;
	int dx = EPntX - SPntX + 2;
	int time = dx >> 4;
	uint8x8x2_t uv_8x8x2;

	uv_8x8x2.val[0] = vdup_n_u8(u);
	uv_8x8x2.val[1] = vdup_n_u8(v);

	memset(y_addr, y, dx);
	memset(yn_addr, y, dx);

	for(j = 0; j < time; j++, i+=16) {
		vst2_u8(uv_addr, uv_8x8x2);
		uv_addr += 16;
	}
	if(dx - i > 8){
		uint16_t uv = (v << 8) + u;
		uint16x4_t uv_16x4 = vdup_n_u16(uv);
		vst1_u16((uint16_t *)uv_addr, uv_16x4);
		uv_addr += 8;
		i += 8;
	}
	for(; i < dx; i += 2){
		*uv_addr++ = u;
		*uv_addr++ = v;
	}
	return ret;
}

static int YUV_Draw_VerLine_neon(unsigned char *YuvBuf, int ImgW, int ImgH, int fmt, int SPntX, int SPntY, int EPntX, int EPntY, int Color, int lineWidth)
{
	uint8_t y = s_color_table[Color].Y;
	uint8_t u = s_color_table[Color].U;
	uint8_t v = s_color_table[Color].V;
	uint8_t *y_addr = YuvBuf + SPntY * ImgW + SPntX;
	uint8_t *uv_addr = YuvBuf + ImgW * ImgH + (SPntY >> 1) * ImgW + SPntX;
	int dy = EPntY - SPntY + 1;

	for(int i = 0; i < dy; i += 2) {
		memset(y_addr, y, lineWidth);
		y_addr += ImgW;
		memset(y_addr, y, lineWidth);
		for(int j = 0; j < lineWidth; j += 2) {
			uv_addr[j] = u;
			uv_addr[j + 1] = v;
		}
		y_addr += ImgW;
		uv_addr += ImgW;
	}

	return 0;
}

/*
 * 1.support max linewidth: 10
 * 2.only support YUVNV12
 * 3.only support little endian
*/
int YUV_Draw_Rect(unsigned char *YuvBuf, int ImgW, int ImgH, int fmt, RECT* Rect, int Color, int lineWidth)
{
	int ret = -1;

	if(YuvBuf == NULL){
		printf("YuvBuf is null!\n");
		return ret;
	}

	if(Rect->top >= Rect->bottom || Rect->left >= Rect->right) {
		printf("Rect(top:%d, left:%d, bottom:%d, right:%d) error!\n", Rect->top, Rect->left, Rect->bottom, Rect->right);
		return ret;
	}
//	if(Rect->top < 0 || Rect->left < 0 || Rect->bottom >= ImgH || Rect->right >= ImgW) {
//		printf("Rect(top:%d, left:%d, bottom:%d, right:%d) error!\n", Rect->top, Rect->left, Rect->bottom, Rect->right);
//		return ret;
//	}
	Rect->top = Rect->top < 0 ? 0 : (Rect->top >= ImgH ? ImgH - 1 : Rect->top);
	Rect->left = Rect->left < 0 ? 0 : (Rect->left >= ImgW ? ImgW - 1 : Rect->left);
	Rect->bottom = Rect->bottom < 0 ? 0 : (Rect->bottom >= ImgH ? ImgH - 1 : Rect->bottom);
	Rect->right = Rect->right < 0 ? 0 : (Rect->right >= ImgW ? ImgW - 1 : Rect->right);

	lineWidth = lineWidth > 10 ? 10 : lineWidth;
	lineWidth = lineWidth <= 0 ? 1 : lineWidth;
	int lineWidth_align = (lineWidth + 1) & 0xFFFFFFFE;

	RECT rect_align;
	rect_align.top = Rect->top & 0xFFFFFFFE;
	rect_align.left = Rect->left & 0xFFFFFFFE;
	rect_align.bottom = Rect->bottom & 0xFFFFFFFE;
	rect_align.right = Rect->right & 0xFFFFFFFE;

	int lineWidth_align_t = rect_align.top + lineWidth_align >= rect_align.bottom ? rect_align.bottom - rect_align.top : lineWidth_align;
	int lineWidth_align_l = rect_align.left + lineWidth_align >= rect_align.right ? rect_align.right - rect_align.left : lineWidth_align;
	int lineWidth_align_b = rect_align.bottom + lineWidth_align >= ImgH - 1 ? ImgH - 1 - rect_align.bottom : lineWidth_align;
	int lineWidth_align_r = rect_align.right + lineWidth_align >= ImgW - 1 ? ImgW - 1 - rect_align.right : lineWidth_align;

	lineWidth_align_b = lineWidth_align_b == 0 ? 1 : lineWidth_align_b;
	lineWidth_align_r = lineWidth_align_r == 0 ? 1 : lineWidth_align_r;
//	printf("lineWidth:%d, lineWidth_align:%d\n", lineWidth, lineWidth_align);
//	printf("lineWidth_align_t:%d, lineWidth_align_b:%d, lineWidth_align_l:%d, lineWidth_align_r:%d\n", lineWidth_align_t, lineWidth_align_b, lineWidth_align_l, lineWidth_align_r);
//	printf("src:top:%d, left:%d, bottom:%d, right:%d\n", Rect->top, Rect->left, Rect->bottom, Rect->right);
//	printf("align:top:%d, left:%d, bottom:%d, right:%d\n", rect_align.top, rect_align.left, rect_align.bottom, rect_align.right);

// top --
	for(int i = 0; i < lineWidth_align_t ; i += 2)
		YUV_Draw_HorLine_neon(YuvBuf, ImgW, ImgH, fmt, rect_align.left, rect_align.top + i , rect_align.right, rect_align.top + i, Color);
// bottom --
	for(int i = 0; i < lineWidth_align_b ; i += 2)
		YUV_Draw_HorLine_neon(YuvBuf, ImgW, ImgH, fmt, rect_align.left,  rect_align.bottom - i, rect_align.right, rect_align.bottom - i, Color);
// left --
	YUV_Draw_VerLine_neon(YuvBuf, ImgW, ImgH, fmt, rect_align.left, rect_align.top, rect_align.left, rect_align.bottom, Color, lineWidth_align_l);
// right --
	YUV_Draw_VerLine_neon(YuvBuf, ImgW, ImgH, fmt, rect_align.right, rect_align.top , rect_align.right, rect_align.bottom, Color, lineWidth_align_r);

	return 0;
}
