int YUY_Draw_Piont(unsigned char * YuvBuf, int ImgW, int ImgH, int fmt,int PntX, int PntY, int Color)
{
   int ret = -1;

   if (PntX >= ImgW || PntY >= ImgH) {
       return ret;
   }

#define ALIGN_DOWN(x, a)         ( ( (x) / (a)) * (a) )
	int X_align = ALIGN_DOWN(PntX, 2);
	int Y_align = ALIGN_DOWN(PntY, 2);
#undef ALIGN_DOWN

   if(YuvBuf == NULL)
       return ret;

    fmt =12;
   switch(fmt)
   {
       case 12://V4L2_PIX_FMT_NV12:
       {
           int Yoffset1 = Y_align * ImgW + X_align;
           int Yoffset2 = Y_align * ImgW + (X_align + 1);
           int Yoffset3 = (Y_align + 1) * ImgW + X_align;
           int Yoffset4 = (Y_align + 1) * ImgW + (X_align + 1);
           int Uoffset,Voffset;

           Uoffset =  ImgH * ImgW + (Y_align / 2) * ImgW + X_align;
           Voffset =  Uoffset + 1;

           YuvBuf[Yoffset1] = s_color_table[Color].Y;
           YuvBuf[Yoffset2] = s_color_table[Color].Y;
           YuvBuf[Yoffset3] = s_color_table[Color].Y;
           YuvBuf[Yoffset4] = s_color_table[Color].Y;
           YuvBuf[Uoffset] = s_color_table[Color].U;
           YuvBuf[Voffset] = s_color_table[Color].V;
       }
           ret = 0;
       break;

       default:
           ret = -2;
       break;
   }
   return ret;
}

int YUY_Draw_Line(unsigned char * YuvBuf, int ImgW, int ImgH, int fmt,int SPntX, int SPntY,int EPntX, int EPntY, int Color,int lineWidth)
{
   int ret = -1;
   if(YuvBuf == NULL)
       return ret;

   if(lineWidth == 0)
       lineWidth = 1;

 //  printf("SPntX=%d,EPntX=%d,SPntY=%d,EPntY=%d\n", SPntX, EPntX, SPntY, EPntY);

   SPntX = (SPntX + lineWidth >= ImgW) ? (ImgW - lineWidth) : (SPntX < 0 ? 0 : SPntX);
   EPntX = (EPntX + lineWidth >= ImgW) ? (ImgW - lineWidth) : (EPntX < 0 ? 0 : EPntX);
   SPntY = (SPntY + lineWidth >= ImgH) ? (ImgH - lineWidth) : (SPntY < 0 ? 0 : SPntY);
   EPntY = (EPntY + lineWidth >= ImgH) ? (ImgH - lineWidth) : (EPntY < 0 ? 0 : EPntY);

   int dx = (SPntX > EPntX) ? (SPntX - EPntX) : (EPntX - SPntX);
   int dy = (SPntY > EPntY) ? (SPntY - EPntY) : (EPntY - SPntY);
   int xstep = (SPntX < EPntX) ? 1 : -1;
   int ystep = (SPntY < EPntY) ? 1 : -1;
   int nstep = 0, eps = 0;
   int pointX = SPntX;
   int pointY = SPntY;
  // printf("dx=%d,dy=%d,xstep=%d,ystep=%d,pointX=%d,pointY=%d\n",
  //         dx, dy, xstep, ystep, pointX, pointY);

    if(dx > dy)
   {
       while(nstep <= dx)
       {
           ret = YUY_Draw_Piont(YuvBuf, ImgW, ImgH, fmt, pointX, pointY, Color);
           if(ret < 0)
               break;

           eps += dy;
           if( (eps << 1) >= dx )
           {
               pointY += ystep;
               eps -= dx;
           }
           pointX += xstep;
           nstep++;
       }
   }
   else
   {
       while(nstep <= dy)
       {
           ret = YUY_Draw_Piont(YuvBuf, ImgW, ImgH, fmt, pointX, pointY, Color);
           if(ret < 0)
               break;

           eps += dx;
           if( (eps << 1) >= dy )
           {
               pointX += xstep;
               eps -= dy;
           }
               pointY += ystep;
               nstep++;
       }
   }
   return ret;
}


